export function translate(locale: Locale, key: string, fallback?: string): string {
  const entry = dictionary[key];
  if (!entry) return fallback ?? key;
  return entry[locale] || entry.en || fallback || key;
}

export function localizedValue(value: Localized | string | null | undefined, locale: Locale): string {
  if (!value) return "";
  if (typeof value === "string") return value;
  return value[locale] || value.en || value.ur || value.ar || "";
}

export function statusKey(value: string | undefined | null): string {
  if (!value) return "";
  return `status.${value}`;
}
